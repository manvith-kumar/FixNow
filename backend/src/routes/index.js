import { Router } from 'express';
import { asyncHandler, ok } from '../utils/http.js';
import { checkConnection } from '../db/pool.js';
import { publicSettings } from '../services/admin.service.js';
import authRoutes from './auth.routes.js';
import usersRoutes from './users.routes.js';
import applicationsRoutes from './applications.routes.js';
import { techniciansRouter, availabilityRouter } from './technicians.routes.js';
import { categoriesRouter, servicesRouter } from './catalogue.routes.js';
import addressesRoutes from './addresses.routes.js';
import bookingsRoutes from './bookings.routes.js';
import quotationsRoutes from './quotations.routes.js';
import paymentsRoutes from './payments.routes.js';
import reviewsRoutes from './reviews.routes.js';
import notificationsRoutes from './notifications.routes.js';
import adminRoutes from './admin.routes.js';

const api = Router();
api.get('/health', asyncHandler(async (_req, res) => { await checkConnection(); ok(res, { status: 'ok', database: 'connected', time: new Date().toISOString() }); }));
api.get('/settings/public', asyncHandler(async (_req, res) => ok(res, await publicSettings())));
api.use('/auth', authRoutes);
api.use('/users', usersRoutes);
api.use('/technician-applications', applicationsRoutes);
api.use('/technicians', techniciansRouter);
api.use('/availability', availabilityRouter);
api.use('/categories', categoriesRouter);
api.use('/services', servicesRouter);
api.use('/addresses', addressesRoutes);
api.use('/bookings', bookingsRoutes);
api.use('/quotations', quotationsRoutes);
api.use('/payments', paymentsRoutes);
api.use('/reviews', reviewsRoutes);
api.use('/notifications', notificationsRoutes);
api.use('/admin', adminRoutes);
export default api;
